// Collects the fits made by tools/tune-lairs.js into the game. Usage: node tools/tune-lairs-merge.js <dir with tune-<class>.json>
const fs = require("fs");
const path = require("path");
const dir = process.argv[2];
const table = {};
["warrior", "mage", "archer", "bard", "assassin"].forEach((classKey) => {
  const fit = JSON.parse(fs.readFileSync(path.join(dir, `tune-${classKey}.json`), "utf8"));
  Object.entries(fit).forEach(([master, levels]) => { (table[master] = table[master] || {})[classKey] = levels; });
});
const lines = Object.entries(table).map(([master, classes]) => `  ${master}: ${JSON.stringify(classes)}`);
fs.writeFileSync(path.join(__dirname, "..", "js", "core", "data.lairtune.js"), `// Generated by tools/tune-lairs.js: master -> class -> rank level -> [life, blows]. Values between ranks are interpolated.\nconst LAIR_TUNE = {\n${lines.join(",\n")}\n};\n`);
console.log("masters", Object.keys(table).length);
